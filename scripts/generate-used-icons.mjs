/**
 * Writes `src/components/icon/huge/used.ts` — the Hugeicons the app refers to
 * by name, so `<Icon>` bundles those up front instead of all ~4,300.
 *
 * Every string literal under `src/` is run through the same `pascalcase` the
 * `Icon` component uses, and kept if it names a Hugeicon. Over-matching (a
 * plain word like 'Mail' that is also an icon) only costs a few bytes; a name
 * built at runtime or sent by the API is still rendered — `Icon` loads the
 * full set on demand for any name missing here.
 *
 * Run after adding an icon: `yarn icons:used`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import pascalcase from 'pascalcase';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = join(ROOT, 'src');
const HUGE_DIR = join(SRC, 'components/icon/huge');
const OUTPUT = join(HUGE_DIR, 'used.ts');

// Files that list every icon name, so scanning them would select everything.
const SKIP = new Set([HUGE_DIR, join(SRC, 'types/huge-icons.type.ts')]);

const EXPORT_LINE = /^export \{ default as (\w+) \} from '\.\/[\w-]+'$/;
const exportLines = new Map(
	readFileSync(join(HUGE_DIR, 'index.ts'), 'utf8')
		.split('\n')
		.map((line) => [line.match(EXPORT_LINE)?.[1], line])
		.filter(([name]) => name),
);

const sourceFiles = (dir) =>
	readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const path = join(dir, entry.name);
		if (SKIP.has(path)) return [];
		if (entry.isDirectory()) return sourceFiles(path);
		return /\.(tsx?|jsx?)$/.test(entry.name) ? [path] : [];
	});

const STRING_LITERAL = /(['"`])([A-Za-z][\w -]*)\1/g;
const used = new Set();
for (const file of sourceFiles(SRC)) {
	for (const [, , value] of readFileSync(file, 'utf8').matchAll(STRING_LITERAL)) {
		const name = pascalcase(value);
		if (exportLines.has(name)) used.add(name);
	}
}

const names = [...used].sort();
writeFileSync(
	OUTPUT,
	[
		`// Generated by scripts/generate-used-icons.mjs — do not edit. Run \`yarn icons:used\`.`,
		...names.map((name) => exportLines.get(name)),
		'',
	].join('\n'),
);
console.log(`${relative(ROOT, OUTPUT)}: ${names.length} of ${exportLines.size} icons`);
